import { render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { MemoryRouter } from "react-router-dom";
import { beforeEach, expect, it, vi } from "vitest";
import Login from "./Login";
import * as api from "@/services/api";
const mocks = vi.hoisted(() => ({ signIn: vi.fn() }));
vi.mock("@/state/AppContext", () => ({ useApp: () => ({ signIn: mocks.signIn, theme: "light" }) }));
vi.mock("@/services/api", () => ({ login: vi.fn(), completeInitialPasswordChange: vi.fn() }));
const userInfo = { id: "member", name: "Member", email: "member@example.com", role: "tenant_user", tenantId: "tn_a", permissions: [] };
beforeEach(() => { vi.clearAllMocks(); localStorage.clear(); });
it("keeps the temporary session out of storage and out of the workspace until the password is changed", async () => {
  vi.mocked(api.login).mockResolvedValue({ token: "restricted", user: userInfo, requiresPasswordChange: true } as never);
  vi.mocked(api.completeInitialPasswordChange).mockResolvedValue({ token: "regular", user: userInfo } as never);
  const user = userEvent.setup(); render(<MemoryRouter><Login /></MemoryRouter>);
  await user.type(screen.getByRole("textbox", { name: "Email" }), "member@example.com");
  await user.type(screen.getByLabelText("Password"), "TemporaryTest9!");
  await user.click(screen.getByRole("button", { name: "Sign in" }));
  await screen.findByRole("heading", { name: "Set your password" });
  expect(mocks.signIn).not.toHaveBeenCalled();
  expect(localStorage.getItem("echosphere.token")).toBeNull();
  await user.type(screen.getByLabelText("New password"), "ChosenPassword8!");
  await user.type(screen.getByLabelText("Confirm new password"), "ChosenPassword8!");
  await user.click(screen.getByRole("button", { name: "Set password and continue" }));
  await waitFor(() => expect(mocks.signIn).toHaveBeenCalledWith(expect.objectContaining({ id: "member" }), "regular"));
  expect(api.completeInitialPasswordChange).toHaveBeenCalledWith("restricted", { currentPassword: "TemporaryTest9!", newPassword: "ChosenPassword8!", confirmPassword: "ChosenPassword8!" });
});
it("keeps a failed password completion on the form with its error", async () => {
  vi.mocked(api.login).mockResolvedValue({ token: "restricted", user: userInfo, requiresPasswordChange: true } as never);
  vi.mocked(api.completeInitialPasswordChange).mockRejectedValue(new Error("The session has expired."));
  const user = userEvent.setup(); render(<MemoryRouter><Login /></MemoryRouter>);
  await user.type(screen.getByRole("textbox", { name: "Email" }), "member@example.com");
  await user.type(screen.getByLabelText("Password"), "TemporaryTest9!");
  await user.click(screen.getByRole("button", { name: "Sign in" }));
  await user.type(await screen.findByLabelText("New password"), "ChosenPassword8!");
  await user.type(screen.getByLabelText("Confirm new password"), "ChosenPassword8!");
  await user.click(screen.getByRole("button", { name: "Set password and continue" }));
  expect(await screen.findByRole("alert")).toHaveTextContent("The session has expired.");
  expect(mocks.signIn).not.toHaveBeenCalled();
});
