    "new clear context questions take priority over the old unresolved "
    "question: keep context_question=true and needs_clarification=false, so "
    "the response stage answers the latest question and resumes the business "
    "question without guessing the old referent. A complete, independent "
    "substantive answer to business_question may instead abandon the old "
    "question and continue the business step: use context_question=false, "
    "decision=null, next_action=continue_workflow and needs_clarification=false, "
