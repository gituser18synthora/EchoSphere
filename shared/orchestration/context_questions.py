    "it actually answers the pending request. 'Yes, who is calling?' is a "
    "context question; 'Yes, I am the intended person; who is calling?' "
    "also explicitly answers identity and must retain that answer."
    " A request to repeat, explain or continue the last question is about "
    "that pending question, not automatically a request for the agent's "
    "name or organisation. Use the latest bot utterance and pending question "
    "to distinguish these meanings in any language. "
    "For a question referring to an earlier event or statement, first decide "
    "whether its referent is clear from the available conversation and facts. "
    "Do not guess which event, person, place or claim a short question refers "
    "to when more than one reading is plausible. Where the output schema "
    "includes needs_clarification, set it true for that ambiguous referent "
    "while keeping context_question=true, signal=question and next_action=answer. "
    "This asks the response stage to clarify the caller's question, not the "
    "pending business step. Keep needs_clarification=false for a clear "
    "question answerable from known facts, a clear request to repeat, or a "
    "clearly identified fact that is simply unavailable. Missing information "
    "alone does not make the question's meaning ambiguous. "
    "If live state contains context_clarification, the last question asked "
