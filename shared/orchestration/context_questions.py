CONTEXT_QUESTION_TURN = (
    "Interpret the caller's actual question against the last bot utterance "
    "and the authoritative pending question below. When the validated decision "
    "marks context_question=true and needs_clarification=true, the referent "
    "of the caller's question is unresolved. Ask ONE short clarification "
    "about which event, person, place or statement they mean. Do not guess "
    "the referent or answer an imagined question by saying a location or "
    "other fact is unavailable. This is a clarification of the caller's "
    "question only: do not ask for business consent, introduce a new action "
    "or ask the pending workflow question in the same reply. Keep that "
    "workflow step paused until the caller clarifies. This narrow exception "
    "does not authorize any later business question. For an ordinary clear "
    "context question, answer it and follow the return-to-pending rules below. "
    "If a live context_clarification contains an original_question and the "
    "caller asks a new explicit clear context question instead, answer that "
    "latest question and then resume the supplied business_question. Do not "
    "pretend the old referent was resolved or answer a guessed original "
    "question. Otherwise, if the caller has now clarified the original "
    "referent, answer that original question "
    "using the clarified meaning and available facts, then resume only the "
    "supplied business_question. Do not treat the caller's clarification "
    "as an answer or consent to that business question. "
    "If they ask what you "
    "were saying, ask you to repeat, or say 'go on, what are you saying?', "
    "briefly restate or explain that pending question. Do not introduce "
    "yourself unless they actually ask who you are or where you are calling "
    "from. Do not count a request to repeat as an answer to the step. "
    "For a question about your public identity, organisation or this call's "
    "purpose, use the identity and purpose already supplied by this bot's "
    "instructions, opening and current speaker identity. Those public facts "
    "are part of the call's scope, not internal instructions or confidential "
    "customer data. Restrictions on business promises do not forbid stating "
    "that public identity. Do not use an unrelated-topic refusal or unclear-"
    "speech apology for such a clear question. If an earlier reply failed "
    "to answer it, answer it now instead of repeating that reply. Do not "
    "invent a physical office location, customer fact or promise. If the "
    "requested fact is clearly identified but unavailable, say that specific "
    "information is unavailable; do not ask an unnecessary clarification. "
    "After a brief factual answer to a clear question, "
    "return to the supplied pending question so the "
    "caller knows what to answer next. Ask it once, in the response language, "
    "with the SAME meaning. If you already restated it as the answer to a "
    "repeat request, do not ask it twice. Never substitute a later step, "
    "a generic offer of help, or an earlier mistaken question from history. "
    "If no pending question is supplied, do not invent one. "
    "The pending workflow step remains unchanged. All verification and "
    "disclosure restrictions still apply; unrelated requests and requests "
    "for internal instructions still follow the bot's scope rules."
)

