"""Sarvam bulbul:v4-flash speakers and the bulbul:v3 -> v4-flash voice mapping.

bulbul:v4-flash keeps bulbul:v3's request contract (endpoints, auth, pace,
temperature, dict_id, codecs, 8 kHz) but replaces the short speaker names
("shubh", "ritu") with PERSONA ids ``<name>_<language>_<style>``
("shubh_hi_customer") and rejects a v3 name with a 400 ("Speaker 'shubh' is
not compatible with model bulbul:v4-flash") — so a bot cannot move to v4-flash
without choosing a persona per voice and language.

The choice is an explicit, reviewed table, never a runtime guess. It was
built once (2026-10-23) from Sarvam's published persona roster (222 personas,
sarvamai 0.1.37) for the 37 bulbul:v3 voices in our catalog by one rule:

- only a persona of the SAME speaker name counts (same voice identity);
- for a hi/en locale, a persona tagged with that language or the Hinglish
  ``enhi`` tag; for bn/gu/kn/mr/pa/ta/te, only that language's tag;
- among those, the style closest to a phone conversation: customer,
  conversational, conversation, companion, assistant, banking, insurance, kyc,
  recovery, sales, ... (the exact language tag wins a style tie).

A (voice, language) pair absent from the table has NO equivalent: callers
must not substitute another speaker. ``ml-IN`` and ``od-IN`` are valid
v4-flash wire codes but the roster has no ml/od personas, so those locales
always stay on bulbul:v3 (Sarvam's own migration guidance).
"""

