class NoV4Equivalent(ValueError):
    """A bulbul:v3 voice has no bulbul:v4-flash persona for this language."""

    def __init__(self, voice: str, language: str) -> None:
        self.voice = voice
        self.language = language
        super().__init__(
            f"Sarvam voice '{voice}' has no bulbul:v4-flash persona for "
            f"{language or 'this language'}; keep this language on bulbul:v3 "
            "or choose a v4-flash persona explicitly"
        )


def is_v4_model(model: str | None) -> bool:
    """bulbul:v4 generation (persona speakers, v3 request contract)."""
    return str(model or "").strip().lower().startswith("bulbul:v4")


def is_v4_persona(voice: str | None) -> bool:
    """A v4 persona id (``<name>_<language>_<style>``), not a v3 short name."""
    return bool(_PERSONA_RE.match(str(voice or "").strip().lower()))


def _base_language(language: str | None) -> str:
    return re.split(r"[-_]", str(language or "").strip().lower(), maxsplit=1)[0]


def v4_persona_for(voice: str | None, language: str | None) -> str | None:
    """The persona a bulbul:v3 ``voice`` maps to for ``language``, or None.

    A persona id is returned unchanged (an operator already chose it).
    """
    name = str(voice or "").strip().lower()
    if not name:
        return None
    if is_v4_persona(name):
        return name
    return V3_TO_V4_PERSONA.get(name, {}).get(_base_language(language))


def v4_speaker(voice: str | None, language: str | None) -> str:
    """Wire speaker for bulbul:v4-flash; raises :class:`NoV4Equivalent`.

    An empty voice means "provider default" and yields Sarvam's default
    persona, mirroring the v3 path's default speaker.
    """
    if not str(voice or "").strip():
        return V4_DEFAULT_PERSONA
    persona = v4_persona_for(voice, language)
    if persona is None:
        raise NoV4Equivalent(str(voice).strip().lower(), str(language or ""))
    return persona


